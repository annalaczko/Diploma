"""Centuria: DINO + handcrafted features with equal block weights (50-50), like
configs/combined/dino_PN_plus_handcrafted_eqw.yaml on the earlier top-5 test set.

Each block (the DINO-P-N-u3 features, 768 dims; the handcrafted features without the Fourier
descriptors, 7 dims) is z-scored on its own (dims with variance < 1e-3 dropped) and divided by
sqrt(its dims), so both blocks have total variance 1 and count the same in euclidean distance.
The z-scores are computed on the images that are clustered, so there is one features.csv for the
full 9-class set and one for the top-5 subset. clustering.standardize stays false (it would undo
the weighting). Nothing is extracted: the features of the finished configs/centuria/models runs.

    python configs/centuria/make_dino_handcrafted.py
    python run_centuria.py --configs configs/centuria/combined --skip-prep

Writes:
  data/pipeline/CENT-DINO-P-N-u3+handcrafted-eqw[-top5]__features/FeatureLearningStep/DINOv3+Handcrafted/
      features.csv, feature_columns.txt (dino_<i>, then the handcrafted names)
  configs/centuria/combined/CENT-DINO-P-N-u3+handcrafted-eqw[-top5].yaml   (MLflow: centuria-eval)
"""

from pathlib import Path

import numpy as np
import pandas as pd
import yaml

REPO = Path(__file__).resolve().parents[2]
PIPELINE = REPO / "data/pipeline"
DINO = "CENT-DINO-P-N-u3"
HANDCRAFTED = "CENT-handcrafted"
HANDCRAFTED_DIMS = ["below_frac", "rim_height_cm", "rim_width_cm", "rim_axis_dist_mean_cm",
                    "rim_axis_dist_min_cm", "rim_axis_dist_max_cm", "rim_thickness_mean_cm"]  # no Fourier
MIN_VARIANCE = 1e-3
LABELS = {"": Path("/data/alaczko/centuria/centuria_labels.csv"),
          "-top5": Path("/data/alaczko/centuria/centuria_labels_top5.csv")}
OUT = REPO / "configs/centuria/combined"


def features_of(config_name: str) -> Path:
    """features.csv of the newest finished run of a configs/centuria/models config."""
    runs = sorted(PIPELINE.glob(f"{config_name}__methodward-metriceuclidean__*/FeatureLearningStep/*/features.csv"))
    if not runs:
        raise SystemExit(f"No finished run of {config_name}")
    return runs[-1]


def read(path: Path) -> pd.DataFrame:
    """features.csv as a table: one row per image (index: file name), one column per dim."""
    table = pd.read_csv(path)
    vectors = np.array([np.array(text.strip("[]").replace(",", " ").split(), dtype=float)
                        for text in table["features"]])
    return pd.DataFrame(vectors, index=table["filename"])


def weighted_block(block: pd.DataFrame) -> pd.DataFrame:
    """z-scored dims (variance >= MIN_VARIANCE), divided by sqrt(their number)."""
    block = block.loc[:, block.var(ddof=0) >= MIN_VARIANCE]
    block = (block - block.mean()) / block.std(ddof=0)
    return block / np.sqrt(block.shape[1])


dino = read(features_of(DINO))
dino.columns = [f"dino_{i}" for i in range(dino.shape[1])]
handcrafted_path = features_of(HANDCRAFTED)
handcrafted = read(handcrafted_path)
handcrafted.columns = handcrafted_path.with_name("feature_columns.txt").read_text().split()
handcrafted = handcrafted[HANDCRAFTED_DIMS]
both = dino.join(handcrafted, how="inner")
dropped = both.isna().any(axis=1)
if dropped.any():
    print(f"{dropped.sum()} images without every handcrafted measure, left out")
    both = both[~dropped]

OUT.mkdir(exist_ok=True)
for suffix, labels_path in LABELS.items():
    ids = set(pd.read_csv(labels_path, dtype={"ID": str})["ID"])
    images = both[both.index.str.rsplit(".", n=1).str[0].isin(ids)]
    combined = pd.concat([weighted_block(images[dino.columns]), weighted_block(images[HANDCRAFTED_DIMS])], axis=1)
    name = f"{DINO}+handcrafted-eqw{suffix}"
    folder = PIPELINE / f"{name}__features/FeatureLearningStep/DINOv3+Handcrafted"
    folder.mkdir(parents=True, exist_ok=True)
    pd.DataFrame({"filename": combined.index,
                  "features": [" ".join(f"{value:.6g}" for value in row) for row in combined.to_numpy()]}
                 ).to_csv(folder / "features.csv", index=False)
    (folder / "feature_columns.txt").write_text("\n".join(combined.columns) + "\n")

    config = {
        "experiment": "centuria-eval",
        "name": name,
        "stop_after": None,
        "sweep": {"clustering.method": ["ward", "average", "weighted", "complete"],
                  "clustering.metric": ["euclidean", "cosine"]},
        "data": {"source": "preprocessed", "labels": str(labels_path), "extract_path": None,
                 "features": str((folder / "features.csv").relative_to(REPO))},
        "clustering": {"cluster_num": 5 if suffix else 9,
                       "standardize": False,  # the blocks are already scaled
                       "min_variance": MIN_VARIANCE, "feature_importance": 10},
    }
    (OUT / f"{name}.yaml").write_text(
        f"# Generated by configs/centuria/make_dino_handcrafted.py: {DINO} + {HANDCRAFTED} (no Fourier),\n"
        f"# equal block weights, {len(combined)} images, {combined.shape[1]} dims "
        f"({images[dino.columns].shape[1]} DINO + {len(HANDCRAFTED_DIMS)} handcrafted before dropping).\n"
        + yaml.safe_dump(config, sort_keys=False, width=200))
    print(f"{name}: {len(combined)} images, {combined.shape[1]} dims -> {OUT / (name + '.yaml')}")
