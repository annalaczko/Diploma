"""Centuria top5: the same models, only on the images of the 5 most frequent classes
(Bowls, Pots, Lids, Jugs, Plates), clustered into 5 clusters - like the earlier test_top5
evaluation. Uses the features of the finished configs/centuria/models runs; nothing is extracted.

    python configs/centuria/make_top5.py
    python run_centuria.py --configs configs/centuria/top5 --skip-prep --gpus 0,1

Writes:
  /data/alaczko/centuria/centuria_labels_top5.csv           ID, TypeRev of the top5 classes
  data/pipeline/CENT-top5-<config>__features/FeatureLearningStep/<Model>/features.csv
                                                            the run's features.csv, top5 images only
  configs/centuria/top5/CENT-top5-<config>.yaml             one config per model (MLflow: centuria-eval)
"""

from pathlib import Path

import pandas as pd
import yaml

REPO = Path(__file__).resolve().parents[2]
LABELS = Path("/data/alaczko/centuria/centuria_labels.csv")
LABELS_TOP5 = LABELS.with_name("centuria_labels_top5.csv")
MODEL_CONFIGS = REPO / "configs/centuria/models"
OUT = REPO / "configs/centuria/top5"

labels = pd.read_csv(LABELS, dtype={"ID": str})
top5 = labels["TypeRev"].value_counts().index[:5]
labels = labels[labels["TypeRev"].isin(top5)]
labels.to_csv(LABELS_TOP5, index=False)
keep = set(labels["ID"])
print(f"{LABELS_TOP5}: {len(labels)} images of {list(top5)}")

OUT.mkdir(exist_ok=True)
for model_config in sorted(MODEL_CONFIGS.glob("*.yaml")):
    source = yaml.safe_load(model_config.read_text())
    name = source["name"]
    # The features are in the first run of the sweep (ward-euclidean); the newest run of it.
    runs = sorted(REPO.glob(f"data/pipeline/{name}__methodward-metriceuclidean__*/FeatureLearningStep/*/features.csv"))
    if not runs:
        print(f"  {name}: no finished run, skipped")
        continue
    features = pd.read_csv(runs[-1])
    features = features[features["filename"].astype(str).str.rsplit(".", n=1).str[0].isin(keep)]
    top5_name = name.replace("CENT-", "CENT-top5-", 1)
    target = REPO / "data/pipeline" / f"{top5_name}__features/FeatureLearningStep" / runs[-1].parent.name / "features.csv"
    target.parent.mkdir(parents=True, exist_ok=True)
    features.to_csv(target, index=False)

    config = {
        "experiment": source["experiment"],
        "name": top5_name,
        "stop_after": None,
        "sweep": source["sweep"],
        "data": {"source": "preprocessed", "labels": str(LABELS_TOP5), "extract_path": None,
                 "features": str(target.relative_to(REPO))},
        "clustering": {**source["clustering"], "cluster_num": 5},
    }
    (OUT / f"{top5_name}.yaml").write_text(
        f"# Centuria top5 (generated by configs/centuria/make_top5.py): {name} features of the\n"
        f"# {len(features)} top5 images ({runs[-1].relative_to(REPO)}), 5 clusters, evaluated.\n"
        + yaml.safe_dump(config, sort_keys=False, width=200))
print(f"{len(list(OUT.glob('*.yaml')))} configs in {OUT}")
